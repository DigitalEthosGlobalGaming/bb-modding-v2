"""Read local 1.09 archives; generate a JSON catalog and allocation-free Rust lookup.

Never modifies game files. Run from any directory; --check verifies generated files.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
FRAMEWORK = ROOT
from archive_formats import unpack_dcx, bnd4_files, read_fmg

TABLES = {
    'EQUIP_PARAM_WEAPON_ST': ('weapon', 0, 11, 'EquipParamWeapon'),
    'EQUIP_PARAM_PROTECTOR_ST': ('protector', 0x10000000, 12, 'EquipParamProtector'),
    'EQUIP_PARAM_ACCESSORY_ST': ('accessory', 0x20000000, 13, 'EquipParamAccessory'),
    'EQUIP_PARAM_GOODS_ST': ('goods', 0x40000000, 10, 'EquipParamGoods'),
}


def slug(name):
    name = re.sub(r'\+(\d+)', r' plus \1', name)
    name = name.replace("'", '').replace('\u2019', '')
    name = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    return re.sub('[^a-z0-9]+', '_', name.lower()).strip('_')


def assign_keys(entries):
    counts = Counter(e['_slug'] for e in entries if e['name_status'] == 'named')
    for e in entries:
        key = e.pop('_slug')
        if e['name_status'] != 'named':
            key = f"unnamed_{e['category']}_{e['param_id']}"
        elif counts[key] > 1:
            key += f"_{e['category']}_{e['param_id']}"
        if not key or key[0].isdigit():
            key = 'item_' + key
        e['key'] = key
    if len({e['key'] for e in entries}) != len(entries):
        raise ValueError('Key collision: explicit disambiguation required')
    return sorted(entries, key=lambda e: e['key'])


def catalog(game):
    paths = ['msg/engus/item.msgbnd.dcx', 'param/gameparam/gameparam.parambnd.dcx']
    sources = [(p, (game / p).read_bytes()) for p in paths]
    msg = unpack_dcx(sources[0][1])
    names = {i: read_fmg(msg[o:o+n]) for _, o, n, i in bnd4_files(msg) if i in (10, 11, 12, 13)}
    if set(names) != {10, 11, 12, 13}:
        raise ValueError('Missing item-name FMG tables')
    params = unpack_dcx(sources[1][1])
    entries, seen = [], set()
    for _, offset, size, _ in bnd4_files(params):
        data = params[offset:offset+size]
        kind = data[12:44].split(b'\0')[0].decode('ascii')
        if kind not in TABLES:
            continue
        if kind in seen:
            raise ValueError('Duplicate parameter table')
        seen.add(kind)
        category, mask, fmg_id, table = TABLES[kind]
        count = struct.unpack_from('<H', data, 10)[0]
        row_end = 64 + count * 24
        if row_end > len(data):
            raise ValueError('Truncated parameter rows')
        ids = set()
        for i in range(count):
            param_id, _, row, _ = struct.unpack_from('<iIQQ', data, 64 + i * 24)
            if not 0 <= param_id < 0x10000000 or not row_end <= row < len(data) or param_id in ids:
                raise ValueError('Unsupported parameter row')
            ids.add(param_id)
            raw = names[fmg_id].get(param_id)
            name = raw.strip() if raw else None
            status = 'missing' if not name else 'placeholder' if name in ('*', 'NOT NEEDED') else 'named'
            entries.append(dict(_slug=slug(name or ''), name=name, name_status=status,
                                category=category, param_id=param_id,
                                encoded_item_id=mask | param_id,
                                encoded_item_id_hex=f'0x{mask | param_id:08X}',
                                param_table=table, name_fmg_id=fmg_id))
    if seen != set(TABLES):
        raise ValueError('Missing equipment parameter tables')
    entries = assign_keys(entries)
    return dict(schema_version=1, game='Bloodborne', title_id='CUSA03173',
                game_version='1.09', language='engus',
                description='Exact parameter rows joined to English name FMGs. Row existence does not imply obtainable or safe to grant. No inferred upgrade IDs or names.',
                sources=[dict(path=p, sha256=hashlib.sha256(b).hexdigest()) for p, b in sources],
                items={e.pop('key'): e for e in entries})


def rust(c):
    items = list(c['items'].items())
    lines = ['// Generated by modding/generate-item-catalog.py; do not edit.',
             'pub static ITEMS: &[Item] = &[']
    for key, e in items:
        name = 'None' if e['name'] is None else 'Some(' + json.dumps(e['name'], ensure_ascii=False) + ')'
        lines.append(f'    Item {{ key: "{key}", name: {name}, category: Category::{e["category"].title()}, param_id: {e["param_id"]}, encoded_item_id: {e["encoded_item_id_hex"]}, name_status: NameStatus::{e["name_status"].title()} }},')
    lines += ['];', 'static ID_INDEX: &[usize] = &[',
              ','.join(str(i) for i in sorted(range(len(items)), key=lambda i: items[i][1]['encoded_item_id'])), '];',
              '/// Exact category-encoded IDs, including explicit upgrade variants.', 'pub mod ids {']
    for key, e in items:
        lines.append(f'    pub const {key.upper()}: u32 = {e["encoded_item_id_hex"]};')
    return '\n'.join(lines + ['}', ''])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--game', type=Path, required=True)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    c = catalog(args.game)
    outputs = {FRAMEWORK / 'sdk/rust/bbmod/local-data/items.json': json.dumps(c, indent=2, ensure_ascii=False) + '\n',
               FRAMEWORK / 'sdk/rust/bbmod/local-data/items_generated.rs': rust(c)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f'Stale generated catalog: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(c["items"])} parameter-backed items; {dict(Counter(e["name_status"] for e in c["items"].values()))}')


if __name__ == '__main__':
    main()
